class For
{
    public static void main(String args[])
    {
        for(int i =0 ;i<=10;i++)
        {
            System.out.println(i);
        }
        for(int j =2;j<=20;j+=2)
        { 
            System.out.println("print no" +j);

        }
        int sum =0;
        for(int k =1;k<=10;k++)
        {
            sum =sum+k;
        }
        System.out.println(sum);

    }
}